"""
Recommendation API Endpoints
Serves personalized recommendations, similar movies, and real-time dot-product ratings.
"""

from fastapi import APIRouter, Query, HTTPException, status
from pydantic import BaseModel, Field
from backend.app.schemas.recommendation import RecommendationResponse, SimilarMoviesResponse
from backend.app.services.recsys_service import recsys_service

router = APIRouter()


class PredictionRequest(BaseModel):
    user_id: int = Field(..., example=1)
    movie_id: int = Field(..., example=50)


class PredictionResponse(BaseModel):
    user_id: int
    movie_id: int
    predicted_rating: float
    computation_mode: str = "Real-time Vector Dot Product"


@router.get("/user/{user_id}", response_model=RecommendationResponse)
async def get_user_recommendations(
    user_id: int,
    limit: int = Query(10, ge=1, le=50, description="Number of recommendations to return")
):
    """
    Returns personalized top-N movie recommendations generated by ALS Matrix Factorization.
    """
    return await recsys_service.get_user_recommendations(user_id=user_id, top_n=limit)


@router.get("/movie/{movie_id}/similar", response_model=SimilarMoviesResponse)
async def get_similar_movies(
    movie_id: int,
    limit: int = Query(5, ge=1, le=20, description="Number of similar movies to return")
):
    """
    Returns the top-N semantically similar movies derived from item latent factor cosine similarity.
    Powers the 'Because You Watched X...' carousels.
    """
    return await recsys_service.get_similar_movies(movie_id=movie_id, top_n=limit)


@router.post("/predict", response_model=PredictionResponse)
async def predict_user_movie_rating(payload: PredictionRequest):
    """
    Calculates the real-time rating prediction r_hat = u_u^T * v_i in microseconds.
    """
    predicted = await recsys_service.predict_rating_realtime(
        user_id=payload.user_id,
        movie_id=payload.movie_id
    )
    if predicted is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Latent vectors not available for user {payload.user_id} or movie {payload.movie_id}."
        )
    return PredictionResponse(
        user_id=payload.user_id,
        movie_id=payload.movie_id,
        predicted_rating=predicted
    )
